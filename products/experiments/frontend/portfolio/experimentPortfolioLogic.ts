import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
    selectors,
} from 'kea'

import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { runWithLimit } from 'scenes/dashboard/dashboardUtils'
import { getExperimentStatus } from 'scenes/experiments/experimentStatus'
import { getExperimentRefreshMode } from 'scenes/experiments/metricQueryUtils'
import { projectLogic } from 'scenes/projectLogic'

import { performQuery } from '~/queries/query'
import { ExperimentQuery, NewExperimentQueryResponse, NodeKind } from '~/queries/schema/schema-general'
import { setLatestVersionsOnQuery } from '~/queries/utils'
import { Experiment, ExperimentStatus } from '~/types'

import { experimentsRetrieve } from 'products/experiments/frontend/generated/api'

import {
    getPortfolioMetricKey,
    getPortfolioMetrics,
    groupPortfolioExperiments,
    isPortfolioMetric,
} from './portfolioUtils'

export interface ExperimentPortfolioLogicProps {
    experiments: Experiment[]
}

export type PortfolioMetricState =
    | { status: 'loaded'; result: NewExperimentQueryResponse }
    | { status: 'unavailable' | 'error' }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface experimentPortfolioLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentProjectId: number | null // projectLogic
    experimentDetails: Record<string, Experiment | null>
    groups: ReturnType<typeof groupPortfolioExperiments>
    metricStates: Record<string, PortfolioMetricState>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface experimentPortfolioLogicActions {
    loadResults: () => void
    setExperimentDetail: (
        experimentId: number,
        experiment: Experiment | null
    ) => {
        experimentId: number
        experiment: Experiment | null
    }
    setMetricState: (
        metricKey: string,
        state: PortfolioMetricState
    ) => {
        metricKey: string
        state: PortfolioMetricState
    }
}

export type experimentPortfolioLogicType = MakeLogicType<
    experimentPortfolioLogicValues,
    experimentPortfolioLogicActions,
    ExperimentPortfolioLogicProps
>

export const experimentPortfolioLogic: LogicWrapper<experimentPortfolioLogicType> = kea<experimentPortfolioLogicType>([
    props({} as ExperimentPortfolioLogicProps),
    key(({ experiments }) => experiments.map((experiment) => `${experiment.id}:${experiment.updated_at}`).join(',')),
    path((key) => ['products', 'experiments', 'portfolio', 'experimentPortfolioLogic', key]),
    connect({
        values: [featureFlagLogic, ['featureFlags'], projectLogic, ['currentProjectId']],
    }),
    actions({
        loadResults: true,
        setExperimentDetail: (experimentId: number, experiment: Experiment | null) => ({ experimentId, experiment }),
        setMetricState: (metricKey: string, state: PortfolioMetricState) => ({ metricKey, state }),
    }),
    reducers({
        experimentDetails: [
            {} as Record<string, Experiment | null>,
            {
                setExperimentDetail: (details, { experimentId, experiment }) => ({
                    ...details,
                    [experimentId]: experiment,
                }),
            },
        ],
        metricStates: [
            {} as Record<string, PortfolioMetricState>,
            { setMetricState: (states, { metricKey, state }) => ({ ...states, [metricKey]: state }) },
        ],
    }),
    selectors({
        groups: [
            (s) => [(_, props: ExperimentPortfolioLogicProps) => props.experiments, s.experimentDetails],
            (experiments: Experiment[], details: Record<string, Experiment | null>) =>
                groupPortfolioExperiments(experiments.map((experiment) => details[experiment.id] || experiment)),
        ],
    }),
    listeners(({ actions, props, values, cache }) => ({
        loadResults: async () => {
            const controller = new AbortController()
            // A one-shot load must finish across tab hides; only replacing or unmounting the view cancels it.
            cache.disposables.add(() => () => controller.abort(), 'portfolio-queries', { pauseOnPageHidden: false })
            const projectId = values.currentProjectId
            const tasks = props.experiments.map((listedExperiment) => async (): Promise<void> => {
                const experimentId = listedExperiment.id
                if (controller.signal.aborted || typeof experimentId !== 'number') {
                    return
                }
                if (!projectId) {
                    actions.setExperimentDetail(experimentId, null)
                    return
                }

                let experiment: Experiment
                try {
                    experiment = (await experimentsRetrieve(String(projectId), experimentId, {
                        signal: controller.signal,
                    })) as unknown as Experiment
                    if (controller.signal.aborted) {
                        return
                    }
                    actions.setExperimentDetail(experimentId, experiment)
                } catch {
                    if (!controller.signal.aborted) {
                        actions.setExperimentDetail(experimentId, null)
                    }
                    return
                }

                if (getExperimentStatus(experiment) === ExperimentStatus.Draft) {
                    return
                }
                const metric = getPortfolioMetrics(experiment)[0]
                if (!metric || !isPortfolioMetric(metric)) {
                    return
                }

                const metricKey = getPortfolioMetricKey(experiment, metric)
                let state: PortfolioMetricState
                try {
                    const response = await performQuery<ExperimentQuery>(
                        setLatestVersionsOnQuery({
                            kind: NodeKind.ExperimentQuery,
                            experiment_id: experimentId,
                            metric,
                        }),
                        { signal: controller.signal },
                        getExperimentRefreshMode(values.featureFlags, false)
                    )
                    state =
                        response.baseline && response.variant_results
                            ? {
                                  status: 'loaded',
                                  result: {
                                      ...response,
                                      baseline: response.baseline,
                                      variant_results: response.variant_results,
                                  },
                              }
                            : { status: 'unavailable' }
                } catch {
                    state = { status: 'error' }
                }
                if (!controller.signal.aborted) {
                    actions.setMetricState(metricKey, state)
                }
            })
            await runWithLimit(tasks, 3)
        },
    })),
    afterMount(({ actions }) => {
        actions.loadResults()
    }),
])
