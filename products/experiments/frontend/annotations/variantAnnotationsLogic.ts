export const variantAnnotationsLogic: LogicWrapper<variantAnnotationsLogicType> = kea<variantAnnotationsLogicType>([
    props({} as VariantAnnotationsLogicProps),
    key(({ experiment }) => experiment.id),
    path((key) => ['products', 'experiments', 'annotations', 'variantAnnotationsLogic', key]),
    connect({ values: [projectLogic, ['currentProjectId'], userLogic, ['user']] }),
    actions({
        setContent: (content: string) => ({ content }),
        setVariantKey: (variantKey: string) => ({ variantKey }),
        setPage: (page: number) => ({ page }),
        editAnnotation: (annotation: ExperimentVariantAnnotationApi) => ({ annotation }),
        startDelete: (annotation: ExperimentVariantAnnotationApi) => ({ annotation }),
        resetEditor: true,
        submitAnnotation: true,
        confirmDelete: true,
        cancelDelete: true,
    }),
    reducers(({ props }) => ({
        content: [
            '',
            {
                setContent: (_, { content }) => content,
                editAnnotation: (_, { annotation }) => annotation.content,
                resetEditor: () => '',
            },
        ],
        variantKey: [
            getExperimentVariants(props.experiment)[0]?.key || '',
            {
                setVariantKey: (_, { variantKey }) => variantKey,
                editAnnotation: (_, { annotation }) => annotation.variant_key,
                resetEditor: () => getExperimentVariants(props.experiment)[0]?.key || '',
            },
        ],
        editingId: [
            null as number | null,
            { editAnnotation: (_, { annotation }) => annotation.id, resetEditor: () => null },
        ],
        editingOriginalVariantKey: [
            null as string | null,
            { editAnnotation: (_, { annotation }) => annotation.variant_key, resetEditor: () => null },
        ],
        annotationToDelete: [
            null as ExperimentVariantAnnotationApi | null,
            {
                startDelete: (_, { annotation }) => annotation,
                cancelDelete: () => null,
                deleteVariantAnnotationSuccess: () => null,
            },
        ],
        page: [1, { setPage: (_, { page }) => page }],
        loadFailed: [
            false,
            {
                loadVariantAnnotations: () => false,
                loadVariantAnnotationsSuccess: () => false,
                loadVariantAnnotationsFailure: () => true,
            },
        ],
        mutationError: [
            null as string | null,
            {
                saveVariantAnnotation: () => null,
                deleteVariantAnnotation: () => null,
                resetEditor: () => null,
                editAnnotation: () => null,
                startDelete: () => null,
                cancelDelete: () => null,
                saveVariantAnnotationFailure: () => 'Could not save the annotation. Try again.',
                deleteVariantAnnotationFailure: () => 'Could not delete the annotation. Try again.',
            },
        ],
    })),
    loaders(({ values, props }) => ({
        annotations: [
            null as AnnotationPage | null,
            {
                loadVariantAnnotations: async (_: void, breakpoint) => {
                    if (!values.currentProjectId || typeof props.experiment.id !== 'number') {
                        return { count: 0, next: null, previous: null, results: [] }
                    }
                    const response = await api.experimentVariantAnnotationsList(String(values.currentProjectId), {
                        experiment_id: props.experiment.id,
                        limit: 20,
                        offset: (values.page - 1) * 20,
                    })
                    breakpoint()
                    return response
                },
            },
        ],
        mutation: [
            null as ExperimentVariantAnnotationApi | null,
            {
                saveVariantAnnotation: async () => {
                    const projectId = values.currentProjectId
                    if (!projectId || typeof props.experiment.id !== 'number') {
                        throw new Error('The experiment is not available.')
                    }
                    const data = { variant_key: values.variantKey, content: values.content.trim() }
                    return values.editingId === null
                        ? await api.experimentVariantAnnotationsCreate(String(projectId), {
                              ...data,
                              experiment: props.experiment.id,
                          })
                        : await api.experimentVariantAnnotationsPartialUpdate(String(projectId), values.editingId, data)
                },
                deleteVariantAnnotation: async (annotationId: number) => {
                    if (!values.currentProjectId) {
                        throw new Error('The project is not available.')
                    }
                    await api.experimentVariantAnnotationsDestroy(String(values.currentProjectId), annotationId)
                    return null
                },
            },
        ],
    })),
    selectors({
        variantOptions: [
            (s) => [
                (_, props: VariantAnnotationsLogicProps) => props.experiment,
                s.editingId,
                s.editingOriginalVariantKey,
            ],
            (experiment: Experiment, editingId: number | null, originalVariantKey: string | null) => {
                const options = getExperimentVariants(experiment).map(({ key }) => ({ value: key, label: key }))
                if (
                    editingId !== null &&
                    originalVariantKey !== null &&
                    !options.some(({ value }) => value === originalVariantKey)
                ) {
                    options.push({ value: originalVariantKey, label: originalVariantKey })
                }
                return options
            },
        ],
        canAnnotate: [
            () => [(_, props: VariantAnnotationsLogicProps) => props.experiment],
            (experiment: Experiment) =>
                userHasAccess(
                    AccessControlResourceType.Experiment,
                    AccessControlLevel.Editor,
                    experiment.user_access_level
                ),
        ],
        canEditAnnotation: [
            (s) => [s.user, s.canAnnotate],
            (user: UserType | null, canAnnotate: boolean) =>
                (annotation: ExperimentVariantAnnotationApi): boolean =>
                    canAnnotate && !!user && annotation.created_by?.id === user.id,
        ],
        canSubmit: [
            (s) => [s.canAnnotate, s.variantOptions, s.variantKey, s.content, s.mutationLoading],
            (
                canAnnotate: boolean,
                options: { value: string; label: string }[],
                variantKey: string,
                content: string,
                loading: boolean
            ): boolean =>
                canAnnotate &&
                !loading &&
                content.trim().length > 0 &&
                content.length <= 2000 &&
                options.some(({ value }) => value === variantKey),
        ],
    }),
    listeners(({ actions, values }) => ({
        setPage: () => actions.loadVariantAnnotations(),
        submitAnnotation: () => {
            if (values.canSubmit && !values.mutationLoading) {
                actions.saveVariantAnnotation()
            }
        },
        confirmDelete: () => {
            if (
                !values.mutationLoading &&
                values.annotationToDelete &&
                values.canEditAnnotation(values.annotationToDelete)
            ) {
                actions.deleteVariantAnnotation(values.annotationToDelete.id)
            }
        },
        saveVariantAnnotationSuccess: () => {
            actions.resetEditor()
            if (values.page !== 1) {
                actions.setPage(1)
            } else {
                actions.loadVariantAnnotations()
            }
        },
        deleteVariantAnnotationSuccess: ({ payload }) => {
            if (payload === values.editingId) {
                actions.resetEditor()
            }
            if (values.page > 1 && values.annotations?.results.length === 1) {
                actions.setPage(values.page - 1)
            } else {
                actions.loadVariantAnnotations()
            }
        },
    })),
    afterMount(({ actions }) => actions.loadVariantAnnotations()),
])
